"""Plan Linux/Python3.8 wheel relocation without importing target packages.

The plan describes publisher-derived bytes only.  pip-generated wrappers and
metadata are classified separately and cannot be accepted from this plan alone.
It assumes the interpreter and installation scheme are independently verified.
"""
from __future__ import annotations

import configparser
import hashlib
import io
import re
import zipfile
from email.parser import BytesParser
from pathlib import PurePosixPath

import p07_pytest6116_prepare_dependencies as audit

PREFIX = '/usr/local'
SITE = PREFIX + '/lib/python3.8/site-packages'
BIN = PREFIX + '/bin'
INTERPRETER = BIN + '/python'
SCRIPT_NAME = re.compile(r'^[A-Za-z0-9][A-Za-z0-9_.-]*$')
RESERVED_SCRIPTS = frozenset({'python', 'python3', 'python3.8'})
ENTRY_TARGET = re.compile(r'^[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*:[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*(?:\s*\[[A-Za-z0-9_,. -]+\])?$')
FIXED_RELOCATIONS = frozenset({
    'nose-1.3.7.data/data/man/man1/nosetests.1',
    'argcomplete-1.12.3.data/scripts/activate-global-python-argcomplete',
    'argcomplete-1.12.3.data/scripts/python-argcomplete-check-easy-install-script',
    'argcomplete-1.12.3.data/scripts/python-argcomplete-tcsh',
    'argcomplete-1.12.3.data/scripts/register-python-argcomplete',
})


def _relative(value):
    if (not value or value.startswith('/') or '\\' in value or '\x00' in value
            or any(part in ('', '.', '..') for part in value.split('/'))):
        raise ValueError('unsafe wheel member path')
    path = PurePosixPath(value)
    if path.is_absolute() or path.as_posix() != value:
        raise ValueError('noncanonical wheel member path')
    return value


def _entry_points(archive, names, info):
    path = info + '/entry_points.txt'
    if path not in names:
        return {}
    parser = configparser.ConfigParser(interpolation=None)
    parser.optionxform = str
    parser.read_string(archive.read(path).decode('utf8'))
    if parser.has_section('gui_scripts') and parser.items('gui_scripts'):
        raise ValueError('GUI wrappers need separate qualification')
    result = dict(parser.items('console_scripts')) if parser.has_section('console_scripts') else {}
    for name, target in result.items():
        if (not SCRIPT_NAME.fullmatch(name) or name in ('pip', 'easy_install') or name in RESERVED_SCRIPTS
                or not ENTRY_TARGET.fullmatch(target.strip())):
            raise ValueError('unsupported generated console script')
    return result


def publisher_wheel_plan(raw: bytes, item: dict, *, allowed_relocations=FIXED_RELOCATIONS):
    """Validate publisher wheel and return expected bytes hashes and wrapper specs.

    Only the five fixed candidate .data/data and .data/scripts paths are allowed
    by default. A caller overriding that set must bind it to trusted policy.
    Unexpected schemes, overlapping entrypoints, interpreter names and shebang
    variants fail closed. RECORD is generated by pip and not asserted here.
    """
    if type(allowed_relocations) is not frozenset:
        raise ValueError('fixed relocation allowlist required')
    audit.inspect_wheel(raw, item)
    with zipfile.ZipFile(io.BytesIO(raw)) as archive:
        names = [entry.filename for entry in archive.infolist() if not entry.is_dir()]
        roots = [name for name in names if name.endswith('.dist-info/METADATA') and '/' not in name.rsplit('/', 1)[0]]
        if len(roots) != 1:
            raise ValueError('exact top-level distribution metadata required')
        info = roots[0].rsplit('/', 1)[0]
        data_root = info.removesuffix('.dist-info') + '.data'
        wheel_metadata = BytesParser().parsebytes(archive.read(info + '/WHEEL'), headersonly=True)
        if wheel_metadata.get_all('Root-Is-Purelib') not in (['true'], ['false']):
            raise ValueError('explicit wheel root scheme required')
        entries = _entry_points(archive, names, info)
        expected = {}
        skipped_record = info + '/RECORD'
        reserved = {info + '/' + name for name in ('INSTALLER', 'REQUESTED', 'direct_url.json')}
        for name in names:
            _relative(name)
            if name == skipped_record:
                continue
            if name in reserved:
                raise ValueError('publisher wheel overlaps pip-generated metadata')
            content = archive.read(name)
            parts = name.split('/')
            kind = 'wheel_root'
            if parts[0].endswith('.data'):
                if (parts[0] != data_root or len(parts) < 3 or parts[1] not in ('data', 'scripts')
                        or name not in allowed_relocations):
                    raise ValueError('unsupported wheel data relocation')
                relative = _relative('/'.join(parts[2:]))
                if parts[1] == 'data':
                    destination = PREFIX + '/' + relative
                    kind = 'wheel_data'
                else:
                    if '/' in relative or not SCRIPT_NAME.fullmatch(relative):
                        raise ValueError('unsafe wheel script name')
                    if relative in RESERVED_SCRIPTS:
                        raise ValueError('wheel script targets the Python interpreter')
                    matchname = relative
                    for suffix in ('.exe', '-script.py', '.pya'):
                        if relative.lower().endswith(suffix):
                            matchname = relative[:-len(suffix)]
                            break
                    if matchname in entries:
                        raise ValueError('wheel script overlaps generated console wrapper')
                    destination = BIN + '/' + relative
                    kind = 'wheel_script'
                    first, sep, rest = content.partition(b'\n')
                    if first.startswith(b'#!python') and first != b'#!python':
                        raise ValueError('unsupported Python shebang variant')
                    if first == b'#!python':
                        content = b'#!' + INTERPRETER.encode('ascii') + b'\n' + (rest if sep else b'')
                        kind = 'wheel_script_shebang_rewritten'
            else:
                if any(part.endswith('.data') for part in parts):
                    raise ValueError('nested data directory unsupported')
                destination = SITE + '/' + name
            if destination in expected:
                raise ValueError('duplicate installed destination')
            expected[destination] = {'sha256': hashlib.sha256(content).hexdigest(),
                                     'size': len(content), 'kind': kind, 'wheel_member': name}
        wrappers = {BIN + '/' + name: {'entry_point': target.strip(), 'kind': 'pip_generated_console_script',
                                       'expected_sha256': None} for name, target in entries.items()}
        if set(wrappers) & set(expected):
            raise ValueError('generated wrapper collides with wheel file')
        return {'distribution': item['name'], 'version': item['version'], 'wheel_sha256': item['sha256'],
                'expected_publisher_files': expected, 'generated_console_scripts': wrappers,
                'generated_metadata_dir': SITE + '/' + info,
                'ordinary_acceptance': False}


def merge_plans(plans):
    """Reject cross-wheel overwrites; retain generated scripts as unverified."""
    files = {}
    wrappers = {}
    for plan in plans:
        for key, value in plan['expected_publisher_files'].items():
            if key in files or key in wrappers:
                raise ValueError('cross-wheel installed destination collision')
            files[key] = value
        for key, value in plan['generated_console_scripts'].items():
            if key in files or key in wrappers:
                raise ValueError('cross-wheel generated script collision')
            wrappers[key] = value
    return {'scope': 'prospective Python3.8 Linux installation plan; not admission',
            'publisher_files': files, 'generated_console_scripts': wrappers,
            'generated_scripts_bytes_verified': False, 'ordinary_acceptance': False}


def verify_publisher_bytes(plan, observed):
    """Compare a caller's safely extracted destination-to-bytes map exactly."""
    expected = plan['publisher_files']
    if set(observed) != set(expected):
        raise ValueError('publisher file inventory differs')
    for name, data in observed.items():
        if type(data) is not bytes or len(data) != expected[name]['size'] or hashlib.sha256(data).hexdigest() != expected[name]['sha256']:
            raise ValueError('installed publisher file differs: ' + name)
    return {'publisher_files_verified': len(expected), 'generated_scripts_bytes_verified': False,
            'ordinary_acceptance': False}
